#!/usr/bin/env node
'use strict';
// Writes INDEX.md: one line per hub item, so an agent can find a resource by reading one small file
// instead of having every description loaded into every session. Run after adding or removing hub items.
const fs = require('node:fs');
const path = require('node:path');

const HUB = __dirname;
const MAX = 110;

function describe(file) {
  const text = fs.readFileSync(file, 'utf8');
  const front = /^---\n([\s\S]*?)\n---/.exec(text)?.[1] ?? '';
  const raw = /^description:\s*(.*)$/m.exec(front)?.[1] ?? '';
  const clean = raw.replace(/^["']|["']$/g, '').replace(/\s+/g, ' ').trim();
  const first = clean.split(/(?<=[.!?])\s/)[0];
  return first.length > MAX ? `${first.slice(0, MAX - 1).trimEnd()}…` : first;
}

function buildIndex(hub = HUB) {
  const md = (dir) => fs.readdirSync(path.join(hub, dir)).filter((f) => f.endsWith('.md')).sort();
  const skills = fs.readdirSync(path.join(hub, 'skills')).filter((d) => fs.existsSync(path.join(hub, 'skills', d, 'SKILL.md'))).sort();
  const line = (name, rel) => `- \`${name}\` (${rel}): ${describe(path.join(hub, rel))}`;
  return [
    '# Resource hub index',
    '',
    'Generated by `build-index.js`; do not edit by hand. Paths are relative to this folder.',
    '',
    `## Skills (${skills.length})`,
    ...skills.map((s) => line(s, `skills/${s}/SKILL.md`)),
    '',
    `## Agents (${md('agents').length})`,
    ...md('agents').map((f) => line(f.slice(0, -3), `agents/${f}`)),
    '',
    `## Commands (${md('commands').length})`,
    ...md('commands').map((f) => line(f.slice(0, -3), `commands/${f}`)),
    '',
  ].join('\n');
}

if (require.main === module) {
  fs.writeFileSync(path.join(HUB, 'INDEX.md'), buildIndex());
  console.log('hub: INDEX.md written');
}
module.exports = { buildIndex };
