test('a product whose kickoff choice is no designed screens skips the look phase and the gate', async () => {
  const kickoff = { version: 1, choices: { design: 'none' } };
  const { root, o } = await newRun({ ...LATE, ...Object.fromEntries(Object.entries(EARLY).filter(([f]) => !f.includes('design-approved') && !f.includes('screens'))), 'docs/spec-approved-page.md': specPage('No screens: standard components throughout.') }, { kickoff });
  o.label('afk', 'spec-approved', 'accepted');
  const r = await check(root);
  assert.deepEqual(r.phases.map((p) => p.name), ['discover', 'ux', 'design', 'spec', 'spec-approved', 'plan', 'build', 'review', 'qa', 'release', 'accepted', 'retro']);
  assert.equal(r.pass, true);
  assert.match(formatReport(r), /design gate: not in this run - the kickoff choice is "None; standard components throughout"/);
});

test('an invalid kickoff file keeps the gate: nothing in it applies', async () => {
  const { root } = await newRun(EARLY, { kickoff: { version: 1, choices: { design: 'none', bogus: 1 } } });
  assert.equal((await check(root)).blocked, 'design-approved');
});

test('the decision is made once, at the first check, and a later kickoff edit only warns', async () => {
  const { root } = await newRun(EARLY);
  write(root, { 'docs/kickoff.json': { version: 1, choices: { design: 'none' } } });
  const r = await check(root);
  assert.equal(r.blocked, 'design-approved');
  assert.match(r.warnings.join('\n'), /kickoff\.json now says no screens are designed, but this run took the design gate at its first check: the gate stays/);

  const skipped = await newRun({}, { kickoff: { version: 1, choices: { design: 'none' } } });
  write(skipped.root, { ...EARLY, 'docs/kickoff.json': { version: 1, choices: { design: 'key' } } });
  const s = await check(skipped.root);
  assert.equal(statusOf(s).look, undefined);
  assert.match(s.warnings.join('\n'), /kickoff\.json now asks for designed screens, but this run left the design gate out at its first check/);
});

test('a run already past the experience phase when the harness is updated is not sent backwards', async () => {
  // No design-approved page, no screens: the run was at system design or later under the old harness.
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'design-gate-old-'));
  const { 'docs/design-approved-page.md': _page, ...old } = EARLY;
  write(root, { ...old, ...LATE, 'docs/spec-approved-page.md': specPage('Pick one of the three looks below.') });
  const o = owner(root, ['afk']);
  const r = await check(root);
  assert.equal(statusOf(r).look, undefined);
  assert.equal(r.blocked, 'spec-approved');
  assert.match(formatReport(r), /design gate: not in this run - this run was past the experience phase when the design gate was added/);
  // Its approval is kept: the next checks do not void it or ask for design-approved.
  o.label('afk', 'spec-approved');
  assert.equal((await check(root)).blocked, 'accepted');
  write(root, { 'docs/design-approved-page.md': DESIGN_PAGE });
  const again = await check(root);
  assert.equal(again.blocked, 'accepted');
  assert.equal(statusOf(again)['design-approved'], undefined);
});

test('a run with a spec-approved approval or a pinned spec issue is past the experience phase too', async () => {
  for (const state of [{ approvals: { 'spec-approved': { files: {}, amends: {} } } }, null]) {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'design-gate-state-'));
    write(root, { 'docs/brief.md': EARLY['docs/brief.md'] });
    if (state) write(root, { '.harness/pipeline/app.gates.json': state });
    else write(root, { '.harness/pipeline/app.spec.json': { spec: 19 } });
    owner(root);
    const r = await check(root);
    assert.match(formatReport(r), /design gate: not in this run/);
  }
});
