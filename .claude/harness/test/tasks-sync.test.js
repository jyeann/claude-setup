'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { parseTasks } = require('../lib/tasks');
const { buildTaskList, closingRefs } = require('../lib/tasks-sync');

const BIN = path.join(__dirname, '..', 'bin');
const TASKS_SYNC = path.join(BIN, 'tasks-sync.js');
const NEXT_TASK = path.join(BIN, 'next-task.js');
const NOW = new Date('2026-11-24T00:00:00Z');

const issue = (number, extra = {}) => ({ number, title: `Ticket ${number}`, state: 'OPEN', labels: ['afk'], body: '', ...extra });

function tmpDir() {
  return fs.mkdtempSync(path.join(os.tmpdir(), 'tasks-sync-'));
}

function git(cwd, ...args) {
  const r = spawnSync('git', args, { cwd, encoding: 'utf8' });
  assert.equal(r.status, 0, r.stderr);
  return r.stdout;
}

function repoWithCommits(messages) {
  const dir = tmpDir();
  git(dir, 'init', '-q');
  for (const m of messages) git(dir, '-c', 'user.email=t@t', '-c', 'user.name=t', 'commit', '-q', '--allow-empty', '-m', m);
  return dir;
}

function pull(dir, issues, args = []) {
  const json = path.join(dir, 'issues.json');
  fs.writeFileSync(json, JSON.stringify(issues));
  return spawnSync(process.execPath, [TASKS_SYNC, 'pull', '--spec', '19', '--from-json', json, ...args], { cwd: dir, encoding: 'utf8' });
}

const byId = (text) => new Map(parseTasks(text).map((t) => [t.id, t]));

test('maps each ticket to task T<number> with its title and AFK/HITL type', () => {
  const { text, errors } = buildTaskList([issue(20), issue(21, { title: 'Pick thresholds', labels: [{ name: 'hitl' }] })], { spec: 19, now: NOW });
  assert.deepEqual(errors, []);
  const t = byId(text);
  assert.equal(t.get('T20').title, 'Ticket 20');
  assert.equal(t.get('T20').type, 'AFK');
  assert.equal(t.get('T21').title, 'Pick thresholds');
  assert.equal(t.get('T21').type, 'HITL');
});

test('writes a generated-by header naming the spec issue and time', () => {
  const { text } = buildTaskList([issue(20)], { spec: 19, now: NOW });
  assert.match(text.split('\n')[0], /Generated by tasks-sync\.js from spec issue #19 at 2026-11-24T00:00:00\.000Z\. Do not edit/);
});

test('reports a ticket with neither afk nor hitl label, naming the issue', () => {
  const { errors } = buildTaskList([issue(20, { labels: ['bug'] })], { spec: 19, now: NOW });
  assert.deepEqual(errors, ['#20 "Ticket 20" needs exactly one of the labels afk or hitl']);
});

test('reports a ticket labelled both afk and hitl', () => {
  const { errors } = buildTaskList([issue(20, { labels: ['afk', 'hitl'] })], { spec: 19, now: NOW });
  assert.equal(errors.length, 1);
});

test('reads blockers from a Blocked by section and from native dependencies', () => {
  const issues = [
    issue(20),
    issue(21),
    issue(22, { body: '## What\n\nstuff #99 not a blocker\n\n## Blocked by\n\n- #20\n- #21\n\n## Notes\n#30 also not' }),
    issue(23, { body: 'Blocked by: #20', blockedBy: [{ number: 21, state: 'OPEN' }] }),
  ];
  const t = byId(buildTaskList(issues, { spec: 19, now: NOW }).text);
  assert.deepEqual(t.get('T22').blockedBy, ['T20', 'T21']);
  assert.deepEqual(t.get('T23').blockedBy, ['T20', 'T21']);
  assert.deepEqual(t.get('T20').blockedBy, []);
});

test('drops a closed blocker outside the spec and blocks on an open one', () => {
  const issues = [
    issue(20, { blockedBy: [{ number: 5, state: 'CLOSED' }] }),
    issue(21, { blockedBy: [{ number: 6, state: 'OPEN' }] }),
    issue(22, { body: '## Blocked by\n\n- #7' }), // state unknown: treated as open
  ];
  const t = byId(buildTaskList(issues, { spec: 19, now: NOW }).text);
  assert.equal(t.get('T20').status, 'todo');
  assert.deepEqual(t.get('T20').blockedBy, []);
  assert.equal(t.get('T21').status, 'blocked');
  assert.equal(t.get('T22').status, 'blocked');
});

test('derives done from a closed issue or a closing commit, todo otherwise', () => {
  const issues = [issue(20, { state: 'closed' }), issue(21), issue(22)];
  const t = byId(buildTaskList(issues, { spec: 19, now: NOW, closedByCommit: new Set([21]) }).text);
  assert.equal(t.get('T20').status, 'done');
  assert.equal(t.get('T21').status, 'done');
  assert.equal(t.get('T22').status, 'todo');
});

test('ignores the spec issue itself and orders tasks by issue number', () => {
  const { text } = buildTaskList([issue(22), issue(19), issue(20)], { spec: 19, now: NOW });
  assert.deepEqual(parseTasks(text).map((t) => t.id), ['T20', 'T22']);
});

test('finds closing keywords in commit messages', () => {
  const refs = closingRefs('feat: x\n\nCloses #20\n---\nfix: y (fixes #21, resolved #22)\n---\nrefs #23\n---\nclose #2x');
  assert.deepEqual([...refs].sort(), [20, 21, 22]);
});

test('pull writes TASKS.md that next-task reads end to end', () => {
  const dir = repoWithCommits(['feat: first slice\n\nCloses #20']);
  try {
    const issues = [issue(20), issue(21, { body: 'Blocked by: #20' }), issue(22, { body: 'Blocked by: #21' }), issue(23, { labels: ['hitl'] })];
    const r = pull(dir, issues);
    assert.equal(r.status, 0, r.stderr);
    assert.match(r.stdout, /wrote TASKS\.md: 4 tasks from spec issue #19/);
    const next = spawnSync(process.execPath, [NEXT_TASK, 'TASKS.md'], { cwd: dir, encoding: 'utf8' });
    assert.equal(next.status, 0);
    assert.equal(next.stdout.trim(), 'T21\tTicket 21');
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('pull --out writes elsewhere and works outside a git repository', () => {
  const dir = tmpDir();
  try {
    const r = pull(dir, { issues: [issue(20)] }, ['--out', 'plan/TASKS.md']);
    assert.equal(r.status, 0, r.stderr);
    assert.equal(byId(fs.readFileSync(path.join(dir, 'plan', 'TASKS.md'), 'utf8')).get('T20').status, 'todo');
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('pull exits 2 and writes nothing when a ticket is invalid', () => {
  const dir = tmpDir();
  try {
    const r = pull(dir, [issue(20, { labels: [] })]);
    assert.equal(r.status, 2);
    assert.match(r.stderr, /#20 "Ticket 20" needs exactly one of the labels afk or hitl/);
    assert.equal(fs.existsSync(path.join(dir, 'TASKS.md')), false);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('pull exits 2 with usage on missing arguments or unreadable JSON', () => {
  const dir = tmpDir();
  try {
    const noSpec = spawnSync(process.execPath, [TASKS_SYNC, 'pull', '--from-json', 'x.json'], { cwd: dir, encoding: 'utf8' });
    assert.equal(noSpec.status, 2);
    assert.match(noSpec.stderr, /usage/i);
    const noJson = spawnSync(process.execPath, [TASKS_SYNC, 'pull', '--spec', '19'], { cwd: dir, encoding: 'utf8' });
    assert.equal(noJson.status, 2);
    assert.match(noJson.stderr, /--from-json/);
    const missing = spawnSync(process.execPath, [TASKS_SYNC, 'pull', '--spec', '19', '--from-json', 'nope.json'], { cwd: dir, encoding: 'utf8' });
    assert.equal(missing.status, 2);
    assert.match(missing.stderr, /cannot read nope\.json/);
    fs.writeFileSync(path.join(dir, 'bad.json'), '{"not":"issues"}');
    const bad = spawnSync(process.execPath, [TASKS_SYNC, 'pull', '--spec', '19', '--from-json', 'bad.json'], { cwd: dir, encoding: 'utf8' });
    assert.equal(bad.status, 2);
    assert.match(bad.stderr, /expected a JSON array of issues/);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});
