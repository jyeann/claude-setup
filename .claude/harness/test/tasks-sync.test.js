'use strict';
// tasks-sync is tested through its CLI (the spec's seam): issue JSON and git commits in, TASKS.md out,
// and next-task.js reading that file is the end-to-end contract.
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { parseTasks } = require('../lib/tasks');

const BIN = path.join(__dirname, '..', 'bin');
const TASKS_SYNC = path.join(BIN, 'tasks-sync.js');
const NEXT_TASK = path.join(BIN, 'next-task.js');

const issue = (number, extra = {}) => ({ number, title: `Ticket ${number}`, state: 'open', labels: ['afk'], body: '', ...extra });

function git(cwd, ...args) {
  const r = spawnSync('git', args, { cwd, encoding: 'utf8' });
  assert.equal(r.status, 0, r.stderr);
  return r.stdout.trim();
}

const commit = (dir, message) => git(dir, '-c', 'user.email=t@t', '-c', 'user.name=t', 'commit', '-q', '--allow-empty', '-m', message);

// Runs `pull --spec 19` in a fresh directory. commits: messages to commit first (git repo only if given).
function pull(input, { commits = null, args = [], setup } = {}) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'tasks-sync-'));
  try {
    if (commits) {
      git(dir, 'init', '-q');
      for (const m of commits) commit(dir, m);
    }
    if (setup) setup(dir);
    fs.writeFileSync(path.join(dir, 'issues.json'), JSON.stringify(input));
    const r = spawnSync(process.execPath, [TASKS_SYNC, 'pull', '--spec', '19', '--from-json', 'issues.json', ...args], { cwd: dir, encoding: 'utf8' });
    const outFile = path.join(dir, args.includes('--out') ? args[args.indexOf('--out') + 1] : 'TASKS.md');
    const text = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : null;
    const next = text === null ? null : spawnSync(process.execPath, [NEXT_TASK, outFile], { encoding: 'utf8' });
    return { ...r, text, tasks: new Map(parseTasks(text || '').map((t) => [t.id, t])), next };
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

function ok(result) {
  assert.equal(result.status, 0, result.stderr);
  return result.tasks;
}

test('maps each ticket to task T<number> with its title and AFK/HITL type', () => {
  const t = ok(pull([issue(20), issue(21, { title: 'Pick thresholds', labels: [{ name: 'hitl' }] })]));
  assert.equal(t.get('T20').title, 'Ticket 20');
  assert.equal(t.get('T20').type, 'AFK');
  assert.equal(t.get('T21').title, 'Pick thresholds');
  assert.equal(t.get('T21').type, 'HITL');
});

