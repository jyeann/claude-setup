'use strict';
// Sizing a change request (#90, spec #88): the change's decisions.md says "Size: fix", "Size: change" or
// "Size: new direction", and the size decides the walk. A fix has no spec phase and no spec-approved gate; it
// ends at accepted on the owner's own issue. A change keeps both gates; a new direction runs phases 1 to 4a
// in full in the change records. A size only goes up: a fix re-sized as a change then waits at spec-approved.
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { PAGE_SECTIONS, checkPipeline, formatReport, defaultReadIssue, parseVerdict, SIZES } = require('../lib/pipeline');

const LONG = 'x'.repeat(320);
const passGate = async () => ({ pass: true, output: 'VERIFY PASSED' });
const tasksFrom = (spec) => `<!-- Generated by tasks-sync.js from spec issue #${spec} at 2026-11-25T00:00:00.000Z. Do not edit: edit the issues and run tasks-sync pull again. -->\n# Tasks\n`;
const tasksMatch = async ({ spec }) => ({ status: 0, stdout: `tasks-sync: TASKS.md matches spec issue #${spec}`, stderr: '' });
const PAGE_STACK = '\n### Stack\n\nNode.js, gate adapter node (proven). Alternative: Vite and React, adapter vitest-stryker (experimental).\n';
const PAGE = `# Spec-approved page\n${PAGE_SECTIONS.map((name) => `\n## ${name}\n\nFilled in for the adder product.\n${name === 'The real choices' ? PAGE_STACK : ''}`).join('')}`;
const DESIGN = `# Design\n${LONG}\n\n## Stack\n\nAdapter: node (proven)\nAlternative: vitest-stryker (experimental)\n`;
const CONFIG = {
  testCommand: 'node --test "tests/*.test.js" "acceptance/*.test.js"',
  adapter: 'node',
  holdout: { command: 'node --test "holdout/*.test.js"' },
  journeys: { command: 'node --test "journeys/*.test.js"', uxFile: '../docs/ux.md' },
};
const N = 40;
const R = `docs/changes/${N}`;

function write(root, files) {
  for (const [rel, text] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true });
    fs.writeFileSync(path.join(root, rel), typeof text === 'string' ? text : JSON.stringify(text));
  }
}

// A product whose first run (spec issue #19) is accepted, with the review, qa and release records of request #40.
async function accepted(size, extra = {}) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'size-'));
  write(root, {
    'docs/brief.md': `# Brief\n## Success criteria\nSC1 a person can add two numbers. ${LONG}`,
    'docs/ux.md': `# UX\n### J1. Add (SC1)\nUC1 the sum is shown. ${LONG}`,
    'docs/design.md': DESIGN,
    'docs/decisions.md': '# Decisions\nSpec issue: #19\nLook: variation B\n',
    'docs/spec-approved-page.md': PAGE,
    'docs/reviews.md': `# Reviews\n${LONG}\nOpen: CRITICAL 0, HIGH 0\n`,
    'docs/qa.md': `# QA\n${LONG}`,
    'docs/retro.md': `# Retro\n${LONG}`,
    'app/spec.md': '# Spec\n',
    'app/TASKS.md': tasksFrom(19),
    'app/verify.config.json': CONFIG,
    'app/acceptance/add.test.js': 'test("adds", () => {});\n',
    'app/src/math.js': 'module.exports = 1;\n',
    'app/README.md': '# App\n```bash\nnode src/math.js\n```\n',
    'app/CHANGELOG.md': '# Changelog\n',
  });
  const first = await checkPipeline({ root, product: 'app', docs: 'docs', runGate: passGate, runTasksCheck: tasksMatch, readIssue: issues({ 19: ['spec-approved', 'accepted'] }) });
  assert.equal(first.pass, true, formatReport(first));
  write(root, {
    [`${R}/decisions.md`]: size === null ? '# Decisions for #40\n' : `# Decisions for #40\nSize: ${size} - sized from the owner's issue\n`,
    [`${R}/TASKS.md`]: tasksFrom(N),
    [`${R}/reviews.md`]: `# Reviews of #40\n${LONG}\nOpen: CRITICAL 0, HIGH 0\n`,
    [`${R}/qa.md`]: `# QA of #40\n${LONG}`,
    'app/CHANGELOG.md': '# Changelog\n\n## Unreleased\n- The total no longer rounds down (#40)\n',
    ...extra,
  });
  return root;
}
const issues = (byNumber) => async ({ spec }) => ({ issue: { number: spec, labels: (byNumber[spec] ?? []).map((name) => ({ name })) } });
const run = (root, readIssue, { runTasksCheck = tasksMatch } = {}) => checkPipeline({ root, product: 'app', docs: 'docs', change: N, runGate: passGate, runTasksCheck, readIssue });
const names = (r) => r.phases.map((p) => p.name);
const statusOf = (r) => Object.fromEntries(r.phases.map((p) => [p.name, p.status]));
const problemsOf = (r, name) => r.phases.find((p) => p.name === name).problems;
const resize = (root, size) => fs.appendFileSync(path.join(root, R, 'decisions.md'), `Size: ${size} - re-sized\n`);

test('the three sizes are fix, change and new direction, smallest first', () => {
  assert.deepEqual(SIZES, ['fix', 'change', 'new direction']);
});

test('a change request with no size line stops at the size phase', async () => {
  const root = await accepted(null);
  const r = await run(root, issues({ [N]: ['spec-approved'] }));
  assert.equal(r.blocked, 'size');
  assert.equal(names(r)[0], 'size');
  assert.match(problemsOf(r, 'size')[0], /docs\/changes\/40\/decisions\.md has no "Size:" line.*fix.*change.*new direction/);
  assert.match(formatReport(r), /INCOMPLETE at phase "size"/);
});

test('a size that is not one of the three is refused', async () => {
  const root = await accepted('small');
  const r = await run(root, issues({ [N]: [] }));
  assert.equal(r.blocked, 'size');
  assert.match(problemsOf(r, 'size')[0], /"Size: small - sized from the owner's issue" is not a size: write fix, change or new direction/);
});

test('a fix run skips the spec and spec-approved and waits only at accepted', async () => {
  const root = await accepted('fix');
  const asked = [];
  const r = await run(root, async (q) => { asked.push(q.spec); return issues({ [N]: ['afk'] })(q); });
  assert.deepEqual(names(r), ['size', 'plan', 'build', 'review', 'release', 'accepted']);
  assert.deepEqual(r.waiting, { gate: 'accepted', spec: N });
  assert.deepEqual([...new Set(asked)], [N]);
  assert.equal(formatReport(r).split('\n').at(-1), 'waiting for owner: spec issue #40 needs label accepted');
  const done = await run(root, issues({ [N]: ['afk', 'accepted'] }));
  assert.equal(done.pass, true, formatReport(done));
});

test('a fix needs no task list: the owner\'s issue is its one ticket', async () => {
  const root = await accepted('fix');
  fs.rmSync(path.join(root, R, 'TASKS.md'));
  const r = await run(root, issues({ [N]: [] }), { runTasksCheck: async () => assert.fail('a fix has no task list to check') });
  assert.equal(statusOf(r).plan, 'done');
  assert.deepEqual(r.waiting, { gate: 'accepted', spec: N });
});

test('a fix still needs an AMEND line for every frozen file it edits', async () => {
  const root = await accepted('fix');
  write(root, { 'app/acceptance/add.test.js': 'test("adds, rounding up", () => {});\n' });
  const r = await run(root, issues({ [N]: [] }));
  assert.equal(r.blocked, 'plan');
  assert.match(problemsOf(r, 'plan').join('\n'), /app\/acceptance\/add\.test\.js changed since the owner last accepted the product.*docs\/changes\/40\/decisions\.md/);
});

test('a fix re-sized as a change then waits at spec-approved, even after its accepted wait', async () => {
  const root = await accepted('fix');
  assert.deepEqual((await run(root, issues({ [N]: [] }))).waiting, { gate: 'accepted', spec: N });
  resize(root, 'change');
  const r = await run(root, issues({ [N]: [] }));
  assert.deepEqual(names(r), ['size', 'spec', 'spec-approved', 'plan', 'build', 'review', 'qa', 'release', 'accepted']);
  assert.equal(statusOf(r).size, 'done');
  assert.deepEqual(r.waiting, { gate: 'spec-approved', spec: N });
  // The re-sized request now needs its change records: a task list from the issue, and qa.
  const next = await run(root, issues({ [N]: ['spec-approved'] }));
  assert.deepEqual(next.waiting, { gate: 'accepted', spec: N });
});

test('a size only goes up: a change cannot be re-sized as a fix to skip spec-approved', async () => {
  const root = await accepted('change');
  assert.deepEqual((await run(root, issues({ [N]: [] }))).waiting, { gate: 'spec-approved', spec: N });
  resize(root, 'fix');
  const r = await run(root, issues({ [N]: [] }));
  assert.equal(r.blocked, 'size');
  assert.equal(r.waiting, undefined);
  assert.match(problemsOf(r, 'size')[0], /#40 was sized change; a size only goes up.*"Size: change"/);
  // Restoring the size lets the run go on, at its spec-approved wait.
  resize(root, 'change');
  assert.deepEqual((await run(root, issues({ [N]: [] }))).waiting, { gate: 'spec-approved', spec: N });
});

test('a new direction runs discover, ux, design and the full spec in the change records before spec-approved', async () => {
  const root = await accepted('new direction');
  const r = await run(root, issues({ [N]: [] }));
  assert.deepEqual(names(r), ['size', 'discover', 'ux', 'design', 'spec', 'spec-approved', 'plan', 'build', 'review', 'qa', 'release', 'accepted']);
  assert.equal(r.blocked, 'discover');
  assert.match(problemsOf(r, 'discover')[0], /product brief is missing: write brief\.md/);
  write(root, { [`${R}/brief.md`]: `# Brief\n## Success criteria\nSC1 a person can split a bill. ${LONG}` });
  assert.match(problemsOf(await run(root, issues({ [N]: [] })), 'ux')[0], /UX design is missing/);
  write(root, { [`${R}/ux.md`]: `# UX\n### J1. Add (SC1)\n${LONG}` });
  assert.match(problemsOf(await run(root, issues({ [N]: [] })), 'design')[0], /system design is missing/);
  write(root, { [`${R}/design.md`]: DESIGN });
  const spec = await run(root, issues({ [N]: [] }));
  assert.equal(spec.blocked, 'spec');
  const said = problemsOf(spec, 'spec').join('\n');
  assert.match(said, /docs\/changes\/40\/decisions\.md has no "Look:" line/);
  assert.match(said, /spec-approved-page\.md is missing/);
  write(root, { [`${R}/spec-approved-page.md`]: PAGE });
  fs.appendFileSync(path.join(root, R, 'decisions.md'), 'Look: variation C\n');
  const waits = await run(root, issues({ [N]: [] }));
  assert.deepEqual(waits.waiting, { gate: 'spec-approved', spec: N });
  assert.equal((await run(root, issues({ [N]: ['spec-approved', 'accepted'] }))).pass, true);
});

test('a change re-sized as a new direction voids its spec approval until the owner judges the new spec', async () => {
  const root = await accepted('change', { [`${R}/change.md`]: '# Change #40\n' });
  assert.deepEqual((await run(root, issues({ [N]: ['spec-approved'] }))).waiting, { gate: 'accepted', spec: N });
  resize(root, 'new direction');
  write(root, {
    [`${R}/brief.md`]: `# Brief\n## Success criteria\nSC1 a person can split a bill. ${LONG}`,
    [`${R}/ux.md`]: `# UX\n### J1. Split (SC1)\n${LONG}`,
    [`${R}/design.md`]: DESIGN,
    [`${R}/spec-approved-page.md`]: PAGE,
  });
  fs.appendFileSync(path.join(root, R, 'decisions.md'), 'Look: variation C\n');
  const r = await run(root, issues({ [N]: ['spec-approved'] }));
  assert.deepEqual(r.waiting, { gate: 'spec-approved', spec: N });
  assert.match(problemsOf(r, 'spec-approved').join('\n'), /docs\/changes\/40\/brief\.md.*changed after the owner approved it at spec-approved/);
});

// ---- layer verdicts per size ----
const PASS = 'verdict: problem=pass impression=pass approach=pass correctness=pass craft=pass';
const redirect = (layer, reason) => PASS.replace(`${layer}=pass`, `${layer}=redirect "${reason}"`);
const offlineGh = () => ({ status: 1, stdout: '', stderr: 'error connecting to api.github.com' });
function owner(root) {
  const comments = [];
  const state = { labels: ['afk'] };
  const save = () => write(root, { 'issue.json': { number: N, labels: state.labels.map((name) => ({ name })), comments } });
  save();
  return {
    read: (q) => defaultReadIssue({ ...q, issueJson: path.join(root, 'issue.json'), run: offlineGh }),
    say(body) { comments.push({ id: 7000 + comments.length, body, created_at: new Date(Date.UTC(2026, 10, 26, 1, comments.length)).toISOString() }); save(); },
    label(...labels) { state.labels = labels; save(); },
  };
}

test('in a new direction, problem, impression and approach go back to discover, ux and design in the change records', async () => {
  const { NEW_DIRECTION_LAYERS } = require('../lib/pipeline');
  assert.deepEqual(['problem', 'impression', 'approach', 'correctness'].map((l) => parseVerdict(redirect(l, 'no'), NEW_DIRECTION_LAYERS).redirects[0].phase), ['discover', 'ux', 'design', 'build']);
  const root = await accepted('new direction', {
    [`${R}/brief.md`]: `# Brief\n## Success criteria\nSC1 a person can split a bill. ${LONG}`,
    [`${R}/ux.md`]: `# UX\n### J1. Split (SC1)\n${LONG}`,
    [`${R}/design.md`]: DESIGN,
    [`${R}/spec-approved-page.md`]: PAGE,
  });
  fs.appendFileSync(path.join(root, R, 'decisions.md'), 'Look: variation C\n');
  const o = owner(root);
  o.say(redirect('impression', 'the split screen is crowded'));
  const r = await run(root, o.read);
  assert.equal(r.blocked, 'ux');
  assert.match(problemsOf(r, 'ux')[0], /owner redirected impression at spec-approved \(round 1 of 3\): "the split screen is crowded"/);
  write(root, { [`${R}/ux.md`]: `# UX\n### J1. Split (SC1)\nOne field per person. ${LONG}` });
  assert.deepEqual((await run(root, o.read)).waiting, { gate: 'spec-approved', spec: N });
});

test('a fix judged wrong on problem, impression or approach at accepted goes back to build, where it is re-sized or redone', async () => {
  const { FIX_LAYERS } = require('../lib/pipeline');
  for (const layer of ['problem', 'impression', 'approach', 'correctness', 'craft']) assert.equal(parseVerdict(redirect(layer, 'no'), FIX_LAYERS).redirects[0].phase, 'build');
  const root = await accepted('fix');
  const o = owner(root);
  o.say(redirect('problem', 'this is new behaviour, not a fix'));
  const r = await run(root, o.read);
  assert.equal(r.blocked, 'build');
  assert.match(problemsOf(r, 'build')[0], /owner redirected problem at accepted/);
  // Re-sized as a change: the walk now waits at spec-approved, before the redirected build comes up.
  resize(root, 'change');
  assert.deepEqual((await run(root, o.read)).waiting, { gate: 'spec-approved', spec: N });
});
