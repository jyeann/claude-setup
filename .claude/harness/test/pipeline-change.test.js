// ---- layer verdicts on the change's issue, from a saved copy of it (gh offline) ----
const PASS = 'verdict: problem=pass impression=pass approach=pass correctness=pass craft=pass';
const redirect = (layer, reason) => PASS.replace(`${layer}=pass`, `${layer}=redirect "${reason}"`);
const offlineGh = () => ({ status: 1, stdout: '', stderr: 'error connecting to api.github.com' });
function owner(root, number = CHANGE) {
  const comments = [];
  const state = { labels: ['afk'] };
  const file = `issue-${number}.json`;
  const save = () => write(root, { [file]: { number, labels: state.labels.map((name) => ({ name })), comments } });
  save();
  return {
    read: (q) => defaultReadIssue({ ...q, issueJson: path.join(root, file), run: offlineGh }),
    say(body) { comments.push({ id: 9000 + comments.length, body, created_at: new Date(Date.UTC(2026, 10, 25, 1, comments.length)).toISOString() }); save(); },
    label(...labels) { state.labels = labels; save(); },
  };
}

test('in a change run problem, impression and approach go back to the change spec, correctness and craft to build', () => {
  const { CHANGE_LAYERS } = require('../lib/pipeline');
  assert.deepEqual(parseVerdict(redirect('impression', 'too busy'), CHANGE_LAYERS).redirects, [{ layer: 'impression', phase: 'spec', reason: 'too busy' }]);
  for (const layer of ['problem', 'approach']) assert.equal(parseVerdict(redirect(layer, 'no'), CHANGE_LAYERS).redirects[0].phase, 'spec');
  for (const layer of ['correctness', 'craft']) assert.equal(parseVerdict(redirect(layer, 'no'), CHANGE_LAYERS).redirects[0].phase, 'build');
  assert.equal(parseVerdict(redirect('impression', 'no')).redirects[0].phase, 'ux', 'a first run keeps its own phases');
});

