function write(root, files) {
  for (const [rel, text] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true });
    fs.writeFileSync(path.join(root, rel), typeof text === 'string' ? text : JSON.stringify(text));
  }
}

// A product whose first run is complete (spec issue #19), plus the records of change #30 unless left out.
function project(overrides = {}) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'change-'));
  write(root, {
    'docs/brief.md': `# Brief\n## Success criteria\nSC1 a person can add two numbers. ${LONG}`,
    'docs/ux.md': `# UX\n### J1. Add (SC1)\nUC1 the sum is shown. ${LONG}`,
    'docs/design.md': `# Design\n${LONG}\n\n## Stack\n\nAdapter: node (proven)\nAlternative: vitest-stryker (experimental)\n`,
    'docs/decisions.md': '# Decisions\nSpec issue: #19\nLook: variation B\n',
    'docs/spec-approved-page.md': PAGE,
    'docs/reviews.md': `# Reviews\n${LONG}\nOpen: CRITICAL 0, HIGH 0\n`,
    'docs/qa.md': `# QA\n${LONG}`,
    'docs/retro.md': `# Retro\n${LONG}`,
    'app/spec.md': '# Spec\n',
    'app/TASKS.md': tasksFrom(19),
    'app/verify.config.json': CONFIG,
    'app/acceptance/add.test.js': 'test("adds", () => {});\n',
    'app/src/math.js': 'module.exports = 1;\n',
    'app/README.md': '# App\n```bash\nnode src/math.js\n```\n',
    'app/CHANGELOG.md': '# Changelog\n',
    ...overrides,
  });
  return root;
}
const CHANGE_RECORDS = {
  [`${R}/TASKS.md`]: tasksFrom(CHANGE),
  [`${R}/reviews.md`]: `# Reviews of change #30\n${LONG}\nOpen: CRITICAL 0, HIGH 0\n`,
  [`${R}/qa.md`]: `# QA of change #30\n${LONG}`,
  'app/CHANGELOG.md': '# Changelog\n\n## Unreleased\n- Subtraction (#30)\n',
};

// Labels per issue, as GitHub returns them.
const issues = (byNumber) => async ({ spec }) => ({ issue: { number: spec, labels: (byNumber[spec] ?? []).map((name) => ({ name })) } });
const FIRST_ACCEPTED = { 19: ['spec-approved', 'accepted'] };
const firstRun = (root, readIssue = issues(FIRST_ACCEPTED)) => checkPipeline({ root, product: 'app', docs: 'docs', runGate: passGate, runTasksCheck: tasksMatch, readIssue });
async function accepted(overrides) {
  const root = project(overrides);
  const r = await firstRun(root);
  assert.equal(r.pass, true, formatReport(r));
  return root;
}
const change = (root, readIssue, { runGate = passGate, runTasksCheck = tasksMatch, number = CHANGE } = {}) => checkPipeline({ root, product: 'app', docs: 'docs', change: number, runGate, runTasksCheck, readIssue });
const statusOf = (r) => Object.fromEntries(r.phases.map((p) => [p.name, p.status]));
const problemsOf = (r, name) => r.phases.find((p) => p.name === name).problems;
const lastLine = (r) => formatReport(r).split('\n').at(-1);
const stateFiles = (root) => Object.fromEntries(fs.readdirSync(path.join(root, '.harness/pipeline')).sort().map((f) => [f, fs.readFileSync(path.join(root, '.harness/pipeline', f), 'utf8')]));

test('a change run walks spec, spec-approved, plan, build, review, qa, release and accepted', async () => {
  const root = await accepted(CHANGE_RECORDS);
  // First seen before the owner accepted it: an issue that already carries accepted cannot start a run.
  assert.deepEqual((await change(root, issues({ [CHANGE]: ['spec-approved'] }))).waiting, { gate: 'accepted', spec: CHANGE });
  const r = await change(root, issues({ [CHANGE]: ['spec-approved', 'accepted'] }));
  assert.deepEqual(r.phases.map((p) => p.name), ['spec', 'spec-approved', 'plan', 'build', 'review', 'qa', 'release', 'accepted']);
  assert.equal(r.pass, true, formatReport(r));
  assert.match(formatReport(r), /PIPELINE COMPLETE$/);
});

