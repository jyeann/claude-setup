const PIPELINE = path.join(__dirname, '..', 'bin', 'pipeline.js');
const LONG = 'x'.repeat(320);
const passGate = async () => ({ pass: true, output: 'VERIFY PASSED' });
const tasksFrom = (spec) => `<!-- Generated by tasks-sync.js from spec issue #${spec} at 2026-11-25T00:00:00.000Z. Do not edit: edit the issues and run tasks-sync pull again. -->\n# Tasks\n`;
const tasksMatch = async ({ spec }) => ({ status: 0, stdout: `tasks-sync: TASKS.md matches spec issue #${spec}`, stderr: '' });
const PAGE_STACK = '\n### Stack\n\nNode.js, gate adapter node (proven). Alternative: Vite and React, adapter vitest-stryker (experimental).\n';
