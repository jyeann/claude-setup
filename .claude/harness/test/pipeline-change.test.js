// ---- the CLI and the Stop hook ----
function fakeGh(byNumber) {
  const bin = fs.mkdtempSync(path.join(os.tmpdir(), 'fake-gh-'));
  const labels = path.join(bin, 'labels.json');
  fs.writeFileSync(labels, JSON.stringify(byNumber));
  fs.writeFileSync(path.join(bin, 'gh'), `#!/usr/bin/env node
const byNumber = JSON.parse(require('node:fs').readFileSync(${JSON.stringify(labels)}, 'utf8'));
const n = Number(process.argv.at(-1).split('/').at(-1));
process.stdout.write(JSON.stringify([{ number: n, labels: (byNumber[n] || []).map((name) => ({ name })) }]));
`, { mode: 0o755 });
  return { bin, set: (next) => fs.writeFileSync(labels, JSON.stringify(next)) };
}
const cli = (root, bin, args) => spawnSync(process.execPath, [PIPELINE, 'check', '--product', 'app', '--docs', 'docs', ...args], { cwd: root, encoding: 'utf8', env: { ...process.env, CLAUDE_PROJECT_DIR: root, PATH: `${bin}${path.delimiter}${process.env.PATH}` } });

test('CLI: --change exits 3 with the waiting line on the change issue, and the Stop hook lets the turn end', async () => {
  const root = await accepted();
  const gh = fakeGh({ 19: ['spec-approved', 'accepted'], [CHANGE]: ['afk'] });
  const waiting = cli(root, gh.bin, ['--change', String(CHANGE)]);
  assert.equal(waiting.status, 3, waiting.stdout + waiting.stderr);
  const line = waiting.stdout.trim().split('\n').at(-1);
  assert.equal(line, 'waiting for owner: spec issue #30 needs label spec-approved');
  const verifyCommand = `node .claude/harness/bin/pipeline.js check --product app --docs docs --change ${CHANGE}`;
  const state = { active: true, verifyCommand, iteration: 1, maxIterations: 10, stallLimit: 3, stallCount: 0, history: [] };
  const result = { pass: false, code: 3, output: waiting.stdout };
  const held = decideStop(state, result);
  assert.equal(held.decision, 'block');
  assert.equal(held.nextState.status, 'waiting-for-owner');
  assert.equal(decideStop(held.nextState, result).decision, 'allow');
  gh.set({ 19: ['spec-approved', 'accepted'], [CHANGE]: ['spec-approved'] });
  const next = cli(root, gh.bin, ['--change', String(CHANGE)]);
  assert.equal(next.status, 1, next.stdout + next.stderr);
  assert.match(next.stdout, /\[2\/8\] spec-approved: done[\s\S]*INCOMPLETE at phase "plan"/);
});

